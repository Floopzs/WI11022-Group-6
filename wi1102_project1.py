# Program VendingMachine
# Simulates a grid-based vending machine using 2D arrays, subprograms, loops, conditionals, and QRIS payment

# DECLARATIONS
# ROWS, COLS : int
# items : array [0..ROWS-1][0..COLS-1] of string
# prices : array [0..ROWS-1][0..COLS-1] of int
# stock : array [0..ROWS-1][0..COLS-1] of int
# row_in, col_in : int
# running : bool
# choice : string


# Procedure Definition: DisplayGrid
def DisplayGrid(items, prices, stock, rows, cols):
    # prints the vending machine layout: items, prices, and stock
    # LOCAL DECLARATIONS
    # r, c : int
    # ALGORITHM
    print("\n=================== VENDING MACHINE ===================")
    for r in range(rows):
        row_str = "Row " + str(r) + " -> "
        for c in range(cols):
            row_str += "[" + str(r) + "][" + str(c) + "] " + items[r][c] + " (Rp" + str(prices[r][c]) + " | Stock: " + str(stock[r][c]) + ")  "
        print(row_str)
    print("=======================================================\n")
    return


# Procedure Definition: ProcessQRISPayment
def ProcessQRISPayment(item_name, price):
    # Displays QRIS payment info and waits for user to press ENTER to confirm payment
    # ALGORITHM
    print("\n------------------- QRIS PAYMENT -------------------")
    print("Item      : " + item_name)
    print("Total Due : Rp" + str(price))
    print("[ QRIS CODE DISPLAYED ]")
    print("----------------------------------------------------")
    input("Press ENTER after scanning and completing payment in app... ")
    print("Payment Verified Successfully!")
    return


# MAIN PROGRAM ALGORITHM
ROWS = 2
COLS = 2

# Populated 2D Arrays for 2x2 Grid Vending Machine
items = [
    ["Cold Water", "Soda Can"],
    ["Potato Chips", "Chocolate Bar"]
]

prices = [
    [3000, 7000],
    [5000, 4000]
]

stock = [
    [3, 2],
    [1, 4]
]

running = True

while (running == True):
    DisplayGrid(items, prices, stock, ROWS, COLS)

    print("Enter item coordinates:")
    row_in = int(input("Enter Row index (0 to " + str(ROWS - 1) + "): "))
    col_in = int(input("Enter Column index (0 to " + str(COLS - 1) + "): "))

    # check if coordinate is valid
    if (row_in >= 0 and row_in < ROWS and col_in >= 0 and col_in < COLS):
        # check stock availability
        if (stock[row_in][col_in] > 0):
            selected_item = items[row_in][col_in]
            selected_price = prices[row_in][col_in]

            # simulated QRIS Payment
            ProcessQRISPayment(selected_item, selected_price)

            # deduct stock
            stock[row_in][col_in] = stock[row_in][col_in] - 1

            print("\n>>> DISPENSING ITEM: " + selected_item + " <<<")
            print("Transaction complete!\n")
        else:
            print("\n[ERROR] " + items[row_in][col_in] + " is OUT OF STOCK!\n")
    else:
        print("\n[ERROR] Invalid coordinate selection! Please try again.\n")

    choice = input("Would you like to buy another item? (y/n): ")
    if (choice != 'y' and choice != 'Y'):
        running = False

print("\nThank you for using the Vending Machine!")